"""Recompile guest code captured while the game runs (an overlay) into one C
file that is built as a DLL and loaded by the runtime (runtime/src/core/dyn.c).

Usage (normally run by scripts/dyncompile.bat):
    python -m ps2recomp.dyn BLOB --base 0x1F6D600 --entries 0x1F70870[,0x...] -o out.c

BLOB is the raw memory of the code region starting at --base.  Calls that
leave the region go through ps2_call()/ps2_jump(), so the module only needs
the runtime symbols the exe exports (host/ps2rt_exports.def).
"""

import argparse
import sys
from pathlib import Path

from .elf import Elf, Segment
from .analysis import Program
from .codegen import FunctionEmitter, fname

PF_R_X = 5


def build_source(data, base, entries, log=print):
    seg = Segment(base, len(data), len(data), 0, PF_R_X, data)
    elf = Elf("<overlay>", entries[0], [seg], raw=data)
    prog = Program(elf, extra_entries=set(entries[1:]), log=log).analyze()
    log("dyn analysis: " + prog.summary())
    funcs = dict(sorted(prog.functions.items()))
    out = ['/* Generated by ps2recomp.dyn - code captured at run time. Do not edit. */',
           '#include "ps2rt.h"', '']
    out += [f"void {fname(a)}(R5900 *c);" for a in funcs]
    out.append("")
    for a, func in funcs.items():
        em = FunctionEmitter(prog, func, funcs, {"branch_toggles": {}})
        out += em.emit()
        for w in em.warnings:
            log("warning: " + w)
    # Entry table: primary entries win over secondary labels.
    table = {}
    for a, func in funcs.items():
        for s in func.secondary:
            table.setdefault(s, (1, func.entry))
    for a in funcs:
        table[a] = (0, a)

    def words(addr):
        off = addr - base
        return [int.from_bytes(data[off + 4 * i:off + 4 * i + 4].ljust(4, b"\0"), "little") for i in range(4)]

    out.append("__declspec(dllexport) const ps2_dyn_entry ps2dyn_table[] = {")
    for addr in sorted(table):
        sec, owner = table[addr]
        w = ", ".join(f"0x{x:08X}u" for x in words(addr))
        out.append(f"    {{0x{addr:08X}u, {sec}u, {fname(owner)}, {{{w}}}}},")
    out.append("};")
    out.append(f"__declspec(dllexport) const uint32_t ps2dyn_count = {len(table)}u;")
    return "\n".join(out) + "\n", len(funcs)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ps2recomp.dyn", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("--base", required=True)
    ap.add_argument("--entries", required=True, help="comma-separated entry addresses")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args(argv)
    data = Path(a.blob).read_bytes()
    base = int(a.base, 0)
    entries = [int(e, 0) for e in a.entries.split(",") if e.strip()]
    for e in entries:
        if not base <= e < base + len(data):
            print(f"error: entry {e:08X} outside the region", file=sys.stderr)
            return 2
    src, n = build_source(data, base, entries)
    Path(a.out).write_text(src, encoding="utf-8", newline="\n")
    print(f"dyn: {n} functions -> {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

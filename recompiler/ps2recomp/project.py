"""Write the generated C sources for an analysed program."""

import os
from pathlib import Path

from .codegen import FunctionEmitter, fname

HEADER = """/* Generated by ps2recomp - do not edit. */
#include "ps2rt.h"
#include "funcs.h"
"""

# Split generated code so files compile in parallel and stay manageable.
MAX_LINES_PER_FILE = 40000


def write_project(prog, outdir, name, elf_path, log=print, patches=(), options=(), branch_toggles=None):
    outdir = Path(outdir)
    gen = outdir / "gen"
    gen.mkdir(parents=True, exist_ok=True)
    for old in gen.glob("funcs_*.c"):
        old.unlink()

    funcs = dict(sorted(prog.functions.items()))
    warnings = []

    with open(gen / "funcs.h", "w", newline="\n") as h:
        h.write("/* Generated by ps2recomp - do not edit. */\n#pragma once\n#include \"ps2rt.h\"\n")
        for a in funcs:
            h.write(f"void {fname(a)}(R5900 *c);\n")

    files = []
    buf, lines, idx = [], 0, 0

    def flush():
        nonlocal buf, lines, idx
        if not buf:
            return
        path = gen / f"funcs_{idx:03d}.c"
        with open(path, "w", newline="\n") as f:
            f.write(HEADER)
            f.write("\n".join(buf))
            f.write("\n")
        files.append(path)
        idx += 1
        buf, lines = [], 0

    for a, func in funcs.items():
        em = FunctionEmitter(prog, func, funcs, {"branch_toggles": branch_toggles or {}})
        out = em.emit()
        warnings.extend(em.warnings)
        buf.extend(out)
        lines += len(out)
        if lines >= MAX_LINES_PER_FILE:
            flush()
    flush()

    # Function table: primary entries win over secondary labels.
    table = {}
    for a, func in funcs.items():
        for s in func.secondary:
            table.setdefault(s, (1, func.entry))
    for a in funcs:
        table[a] = (0, a)
    elf_size = os.path.getsize(elf_path)
    image_path = str(Path(elf_path).resolve()).replace("\\", "/").replace('"', '\\"')
    with open(gen / "functable.c", "w", newline="\n") as f:
        f.write(HEADER)
        f.write("const ps2_func_entry ps2_func_table[] = {\n")
        for addr in sorted(table):
            sec, owner = table[addr]
            f.write(f"    {{0x{addr:08X}u, {sec}, {fname(owner)}}},\n")
        f.write("};\n")
        f.write(f"const uint32_t ps2_func_count = {len(table)};\n")
        safe_name = name.replace("\\", "_").replace('"', "_")
        f.write(f'const char ps2_game_name[] = "{safe_name}";\n')
        # Runtime pnach patches (data writes and conditional codes).
        f.write("const ps2_patch ps2_patches[] = {\n")
        for p in patches:
            ca = p.cond_addr if p.has_cond else 0
            f.write(f"    {{0x{p.addr:08X}u, 0x{p.value & 0xFFFFFFFF:08X}u, "
                    f"0x{ca:08X}u, 0x{p.cond_value:04X}u, {p.size}u, {p.option}}},\n")
        if not patches:
            f.write("    {0, 0, 0, 0, 0, -1}\n")
        f.write("};\n")
        f.write(f"const uint32_t ps2_patch_count = {len(patches)}u;\n")
        # Game options switchable at run time (ps2native.ini: <name>=1).
        f.write("const char *const ps2_option_names[] = {"
                + "".join(f'"{o}", ' for o in options) + "0};\n")
        f.write(f"const uint32_t ps2_option_count = {len(options)}u;\n")
        # gcc: embed the ELF with .incbin.  MSVC builds embed it as a Win32
        # resource (image.rc) and the host provides ps2_get_elf_image().
        f.write("#if defined(__GNUC__) && !defined(PS2_IMAGE_RESOURCE)\n")
        f.write("extern const unsigned char ps2_elf_image[];\n")
        f.write("const unsigned char *ps2_get_elf_image(uint32_t *size)\n{\n")
        f.write(f"    *size = {elf_size}u;\n    return ps2_elf_image;\n}}\n")
        f.write("__asm__(\".section .rdata,\\\"dr\\\"\\n\"\n")
        f.write("        \".balign 16\\n\"\n")
        f.write("        \".globl ps2_elf_image\\n\"\n")
        f.write("        \"ps2_elf_image:\\n\"\n")
        f.write(f"        \".incbin \\\"{image_path}\\\"\\n\"\n")
        f.write("        \".text\\n\");\n")
        f.write("#endif\n")
    files.append(gen / "functable.c")
    with open(gen / "image.rc", "w", newline="\n") as f:
        f.write(f'PS2ELF RCDATA "{image_path}"\n')

    with open(outdir / "recomp_report.txt", "w", newline="\n") as r:
        r.write(f"input: {elf_path}\n")
        r.write(prog.summary() + "\n\n")
        bad = [f for f in funcs.values() if f.invalid or f.bad]
        if bad:
            r.write("functions with invalid instructions or flow leaving code:\n")
            for f in bad:
                extra = ", ".join(f"{b:08X}" for b in sorted(f.bad))
                r.write(f"  {f.entry:08X} {f.name or ''} {'invalid' if f.invalid else ''} {extra}\n")
            r.write("\n")
        if warnings:
            r.write("code generation warnings:\n")
            for w in warnings:
                r.write(f"  {w}\n")
    return files, warnings

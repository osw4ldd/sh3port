"""Launcher translations.  T(key, **fmt) returns the text in the current
language, falling back to English and then to the key itself."""

LANGUAGES = [
    ("tr", "Türkçe"), ("en", "English"), ("es", "Español"), ("pt", "Português (BR)"),
    ("fr", "Français"), ("de", "Deutsch"), ("it", "Italiano"), ("ru", "Русский"),
    ("pl", "Polski"), ("ja", "日本語"), ("ko", "한국어"), ("zh", "简体中文"),
]

# Windows primary language ids -> our codes.
WINDOWS_LANGS = {0x1F: "tr", 0x09: "en", 0x0A: "es", 0x16: "pt", 0x0C: "fr", 0x07: "de",
                 0x10: "it", 0x19: "ru", 0x15: "pl", 0x11: "ja", 0x12: "ko", 0x04: "zh"}

# UI font per language (CJK need fonts that contain their glyphs).
FONTS = {"ja": "Yu Gothic UI", "ko": "Malgun Gothic", "zh": "Microsoft YaHei UI"}

_current = "tr"


def set_language(code):
    global _current
    _current = code if code in STRINGS else "en"


def language():
    return _current


def T(key, **fmt):
    text = STRINGS.get(_current, {}).get(key) or STRINGS["en"].get(key) or key
    return text.format(**fmt) if fmt else text


def system_language():
    try:
        import ctypes
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
        return WINDOWS_LANGS.get(lid, "en")
    except (OSError, AttributeError):
        return "en"



{
    u128 t; const u128 a = c->r[rs], b = c->r[rt]; MMI_UNUSED;
    t.UW[0] = b.UW[0]; t.UW[1] = a.UW[0]; t.UW[2] = b.UW[1]; t.UW[3] = a.UW[1];
    MMI_STORE(t);
}

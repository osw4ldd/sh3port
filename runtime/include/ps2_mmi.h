static inline void MMI_PEXT5(MMI_ARGS)
{
    u128 t; MMI_UNUSED;
    for (int i = 0; i < 4; i++) {
        uint32_t x = c->r[rt].UW[i];
        t.UW[i] = ((x & 0x1F) << 3) | ((x & 0x3E0) << 6) | ((x & 0x7C00) << 9) | ((x & 0x8000) << 16);
    }
    MMI_STORE(t);
}
static inline void MMI_PPAC5(MMI_ARGS)
{
    u128 t; MMI_UNUSED;
    for (int i = 0; i < 4; i++) {
        uint32_t x = c->r[rt].UW[i];
        t.UW[i] = ((x >> 3) & 0x1F) | ((x >> 6) & 0x3E0) | ((x >> 9) & 0x7C00) | ((x >> 16) & 0x8000);
    }
    MMI_STORE(t);
}
